def render_script(plan: dict[str, object]) -> str:
    compact = json.dumps(plan, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    encoded = base64.b64encode(compact.encode("utf-8")).decode("ascii")
    return SCRIPT_TEMPLATE.replace("__PLAN_BASE64__", encoded)


def compile_simulation(
    spec: SimulationSpec, spec_path: Path, output_dir: str | Path
) -> dict[str, object]:
    run_dir = prepare_output_dir(output_dir)
    input_value = (
        spec.inputs.project_file if spec.mode is Mode.TEMPLATE else spec.inputs.geometry_file
    )
    input_path = resolve_input_path(spec_path, input_value)
    assert input_path is not None

    normalized_path = safe_join(run_dir, "normalized-simulation.yaml")
    normalized_path.write_text(dump_normalized_yaml(spec), encoding="utf-8")
    plan = build_mechanical_plan(spec, spec_path, input_path)
    plan_path = safe_join(run_dir, "mechanical-plan.json")
    plan_path.write_text(json.dumps(plan, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    script_path = safe_join(run_dir, "generated-mechanical.py")
    script_path.write_text(render_script(plan), encoding="utf-8", newline="\n")
    environment_path = safe_join(run_dir, "environment.json")
    environment_path.write_text(
        json.dumps(environment_snapshot(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    manifest = initial_manifest(
        run_dir=run_dir,
        input_path=input_path,
        spec_path=spec_path,
        normalized_path=normalized_path,
        script_path=script_path,
        execution_mode=spec.execution.backend,
        transport_mode=spec.execution.transport_mode,
    )
    manifest_path = safe_join(run_dir, "run-manifest.json")
    for path in (plan_path, environment_path, manifest_path):
        add_artifact(manifest, run_dir, path)
    manifest["commands_and_checks"].append("schema validation")
    manifest["commands_and_checks"].append("deterministic Mechanical compilation")
    write_manifest(manifest_path, manifest)
    return {
        "run_directory": str(run_dir),
        "normalized_spec": str(normalized_path),
        "mechanical_plan": str(plan_path),
        "generated_script": str(script_path),
        "manifest": str(manifest_path),
        "environment": str(environment_path),
    }
