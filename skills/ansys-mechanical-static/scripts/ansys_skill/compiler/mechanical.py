def scope_location(scope_id):
    if scope_id in CREATED_SCOPES:
        return CREATED_SCOPES[scope_id]
    scope = next(item for item in PLAN["scopes"] if item["id"] == scope_id)
    if scope["kind"] in ("named_selection", "object_name"):
        obj = MechanicalCompat.exact_object(scope["name"])
        if scope["kind"] == "named_selection":
            obj = MechanicalCompat.assert_object_type(
                obj, {"namedselection"}, "scope:{}".format(scope_id)
            )
        CREATED_SCOPES[scope_id] = obj
        return obj
    if scope["kind"] != "axis_extreme_face":
        raise TextToAnsysError("Unsupported scope kind: {}".format(scope["kind"]))

    body = MechanicalCompat.exact_geo_body(scope.get("body"))
    axis_index = {"x": 0, "y": 1, "z": 2}[scope["axis"]]
    try:
        geometry_unit = str(ExtAPI.DataModel.GeoData.Unit)
        tolerance = float(
            units.ConvertUnit(
                float(scope["tolerance_canonical_m"]),
                fromUnit="m",
                toUnit=geometry_unit,
            )
        )
    except Exception as exc:
        raise UnsupportedMechanicalApi(
            "Geometry unit conversion required by axis_extreme_face is unavailable: {}".format(exc)
        )
    entries = [
        (face, MechanicalCompat.face_data(face, geometry_unit)) for face in body.Faces
    ]
    if not entries:
        raise TextToAnsysError("axis_extreme_face found no faces")
    coordinates = [entry[1]["centroid"][axis_index] for entry in entries]
    target = min(coordinates) if scope["extreme"] == "min" else max(coordinates)
    candidates = [
        entry for entry in entries if abs(entry[1]["centroid"][axis_index] - target) <= tolerance
    ]
    FACE_SELECTIONS.append(
        {
            "scope_id": scope_id,
            "axis": scope["axis"],
            "extreme": scope["extreme"],
            "target": target,
            "geometry_length_unit": geometry_unit,
            "tolerance_original": scope["tolerance"],
            "tolerance_canonical_m": scope["tolerance_canonical_m"],
            "tolerance_geometry_unit": tolerance,
            "candidates": [entry[1] for entry in entries],
            "matched": [entry[1] for entry in candidates],
        }
    )
    if len(candidates) != 1:
        raise TextToAnsysError(
            "axis_extreme_face {!r} expected one face; found {}".format(scope_id, len(candidates))
        )
    selection = MechanicalCompat.selection_from_entities([candidates[0][0]])
    named_selection = Model.AddNamedSelection()
    named_selection.Name = scope["dpf_named_selection"]
    named_selection.Location = selection
    CREATED_SCOPES[scope_id] = named_selection
    return named_selection


def prepare_model():
    input_path = MechanicalCompat.input_path()
    if PLAN["mode"] == "template":
        App.open(input_path)
        analysis = MechanicalCompat.exact_object(PLAN["analysis"]["object_name"])
    else:
        App.new()
        geometry_import = Model.AddGeometryImportGroup().AddGeometryImport()
        preferences = Ansys.ACT.Mechanical.Utilities.GeometryImportPreferences()
        geometry_import.Import(
            input_path,
            Ansys.Mechanical.DataModel.Enums.GeometryImportPreference.Format.Automatic,
            preferences,
        )
        analysis = Model.AddStaticStructuralAnalysis()
        analysis.Name = "text-to-ansys static structural"
    ANALYSIS_INFO.update(MechanicalCompat.assert_static_structural(analysis))
    CREATED["analysis"] = analysis
    return analysis


def apply_materials():
    for body_plan in PLAN["bodies"]:
        if body_plan["material_source"] != "engineering_data":
            raise UnsupportedMechanicalApi(
                "Custom material authoring is intentionally disabled in v1"
            )
        body = MechanicalCompat.exact_tree_body(body_plan["name"])
        body.Material = body_plan["material_name"]


def apply_mesh():
    Model.Mesh.ElementSize = Quantity(PLAN["mesh"]["global_element_size"])
    order = PLAN["mesh"]["element_order"]
    if order != "program_controlled":
        try:
            Model.Mesh.ElementOrder = getattr(
                Ansys.Mechanical.DataModel.Enums.ElementOrder,
                "Linear" if order == "linear" else "Quadratic",
            )
        except Exception as exc:
            raise UnsupportedMechanicalApi("Mesh element-order API is unavailable: {}".format(exc))
    Model.Mesh.GenerateMesh()


def apply_supports(analysis):
    for item in PLAN["supports"]:
        if PLAN["mode"] == "template":
            support = MechanicalCompat.assert_object_type(
                MechanicalCompat.exact_object(item["object_name"]),
                {"fixedsupport"},
                "support:{}".format(item["id"]),
            )
        else:
            support = analysis.AddFixedSupport()
            support.Name = item["id"]
        support.Location = scope_location(item["scope"])
        CREATED[item["id"]] = support


def apply_loads(analysis):
    for item in PLAN["loads"]:
        if PLAN["mode"] == "template":
            expected = {
                "force": {"force"},
                "pressure": {"pressure"},
                "gravity": {"earthgravity"},
            }[item["type"]]
            load = MechanicalCompat.assert_object_type(
                MechanicalCompat.exact_object(item["object_name"]),
                expected,
                "load:{}".format(item["id"]),
            )
        elif item["type"] == "force":
            load = analysis.AddForce()
        elif item["type"] == "pressure":
            load = analysis.AddPressure()
        elif item["type"] == "gravity":
            load = analysis.AddEarthGravity()
        else:
            raise TextToAnsysError("Unsupported load type: {}".format(item["type"]))
        if PLAN["mode"] != "template":
            load.Name = item["id"]
        if item.get("scope"):
            load.Location = scope_location(item["scope"])
        if item["type"] == "force":
            MechanicalCompat.set_components(load, item["components"])
        elif item["type"] == "gravity":
            load.Direction = getattr(
                Ansys.Mechanical.DataModel.Enums.GravityOrientationType,
                item["gravity_orientation"],
            )
        else:
            load.Magnitude.Output.DiscreteValues = [Quantity(item["magnitude"])]
        CREATED[item["id"]] = load


def apply_results(analysis):
    solution = analysis.Solution
    for item in PLAN["requested_results"]:
        if item["type"] in ("solver_messages", "node_count", "element_count"):
            continue
        if PLAN["mode"] == "template":
            expected = {
                "total_deformation": {"totaldeformation"},
                "directional_deformation": {"directionaldeformation"},
                "equivalent_von_mises_stress": {"equivalentstress"},
                "reaction_force": {"forcereaction"},
            }[item["type"]]
            result = MechanicalCompat.assert_object_type(
                MechanicalCompat.exact_object(item["object_name"]),
                expected,
                "result:{}".format(item["id"]),
            )
        elif item["type"] == "total_deformation":
            result = solution.AddTotalDeformation()
        elif item["type"] == "directional_deformation":
            result = solution.AddDirectionalDeformation()
            MechanicalCompat.set_directional_axis(result, item["direction"])
        elif item["type"] == "equivalent_von_mises_stress":
            result = solution.AddEquivalentStress()
        elif item["type"] == "reaction_force":
            result = solution.AddForceReaction()
            result.BoundaryConditionSelection = CREATED[item["support"]]
        else:
            raise TextToAnsysError("Unsupported result type: {}".format(item["type"]))
        if PLAN["mode"] != "template":
            result.Name = item["id"]
        if item.get("scope") and hasattr(result, "Location"):
            result.Location = scope_location(item["scope"])
        CREATED[item["id"]] = result


def collect_messages():
    collected = []
    try:
        for message in ExtAPI.Application.Messages:
            collected.append(
                {
                    "severity": str(getattr(message, "Severity", "UNKNOWN")),
                    "text": str(getattr(message, "DisplayString", message)),
                }
            )
    except Exception as exc:
        collected.append({"severity": "UNKNOWN", "text": "Message API unavailable: {}".format(exc)})
    return collected


def export_current_image(filename):
    settings = Ansys.Mechanical.Graphics.GraphicsImageExportSettings()
    settings.Resolution = (
        Ansys.Mechanical.DataModel.Enums.GraphicsResolutionType.EnhancedResolution
    )
    settings.Background = Ansys.Mechanical.DataModel.Enums.GraphicsBackgroundType.White
    settings.CurrentGraphicsDisplay = True
    settings.Width = 1280
    settings.Height = 720
    ExtAPI.Graphics.ExportImage(
        os.path.join(os.getcwd(), filename),
        Ansys.Mechanical.DataModel.Enums.GraphicsImageExportFormat.PNG,
        settings,
    )


def export_images():
    states = []
    if not PLAN["output"].get("export_images"):
        return [{"name": "visual_review", "status": "NOT_RUN", "reason": "disabled"}]
    try:
        Model.Mesh.Activate()
        export_current_image("mesh.png")
        states.append({"name": "mesh.png", "status": "PASS"})
    except Exception as exc:
        states.append({"name": "mesh.png", "status": "NOT_RUN", "reason": str(exc)})
    for result_type, filename in (
        ("total_deformation", "total-deformation.png"),
        ("equivalent_von_mises_stress", "equivalent-stress.png"),
    ):
        item = next((x for x in PLAN["requested_results"] if x["type"] == result_type), None)
        if not item or item["id"] not in CREATED:
            states.append({"name": filename, "status": "NOT_RUN", "reason": "result not requested"})
            continue
        try:
            CREATED[item["id"]].Activate()
            export_current_image(filename)
            states.append({"name": filename, "status": "PASS"})
        except Exception as exc:
            states.append({"name": filename, "status": "NOT_RUN", "reason": str(exc)})
    return states


